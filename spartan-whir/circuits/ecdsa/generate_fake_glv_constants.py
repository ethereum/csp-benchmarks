#!/usr/bin/env python3
"""Generate KoalaBear-safe fake-GLV constants from curve integer arithmetic."""

from pathlib import Path
from generate_constants import CURVES, assignments, limbs


def add(left, right, curve):
    if left is None:
        return right
    if right is None:
        return left
    p, a = curve["prime"], curve["a"]
    x, y = left
    xx, yy = right
    if x == xx and (y + yy) % p == 0:
        return None
    slope = ((3*x*x+a)*pow(2*y, -1, p) if left == right
             else (yy-y)*pow(xx-x, -1, p)) % p
    rx = (slope*slope-x-xx) % p
    return rx, (slope*(x-rx)-y) % p


def multiply(scalar, point, curve):
    result = None
    while scalar:
        if scalar & 1:
            result = add(result, point, curve)
        point = add(point, point, curve)
        scalar >>= 1
    return result


def point_function(name, values):
    return (
        f"function {name}(p256) {{\n    var out[2][22];\n"
        "    if (p256 == 1) {\n"
        + assignments([limbs(v) for v in values[1]])
        + "    } else {\n"
        + assignments([limbs(v) for v in values[0]])
        + "    }\n    return out;\n}\n"
    )


def generate():
    lam = 0x5363AD4CC05C30E0A5261C028812645A122E22EA20816678DF02967C1B23BD72
    beta = 0x7AE96A2B657C07106E64479EAC3434E99CF0497512F58995C1396C28719501EE
    k1 = CURVES[0]
    assert pow(lam, 3, k1["order"]) == 1 and lam != 1
    assert pow(beta, 3, k1["prime"]) == 1 and beta != 1
    generator = (k1["gx"], k1["gy"])
    assert multiply(lam, generator, k1) == (beta*generator[0] % k1["prime"], generator[1])
    sentinels, targets = [], []
    for p256, curve in enumerate(CURVES):
        generator = (curve["gx"], curve["gy"])
        sentinel = multiply(12345678901234567890, generator, curve)
        multiplier = ((1 << 128)-1)//3 if p256 else (1 << 64)-1
        target = multiply(multiplier, sentinel, curve)
        assert sentinel is not None and target is not None
        sentinels.append(sentinel)
        targets.append(target)
    text = "pragma circom 2.2.0;\n\n// Generated by generate_fake_glv_constants.py.\n"
    for name, value in (("kb_glv_lambda", lam), ("kb_glv_beta", beta)):
        text += f"\nfunction {name}() {{\n    var out[22];\n"
        text += assignments(limbs(value)) + "    return out;\n}\n"
    text += "\n" + point_function("kb_glv_sentinel", sentinels)
    text += "\n" + point_function("kb_glv_target", targets)
    return text


if __name__ == "__main__":
    Path(__file__).with_name("fake_glv_constants.circom").write_text(generate())
