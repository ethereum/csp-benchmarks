#!/usr/bin/env python3
"""Generate width-12 signed-digit comb tables as 12-bit curve coordinates."""

from pathlib import Path

from generate_constants import CURVES, limbs


WINDOWS = 22
WIDTH = 12
ENTRIES = 1 << (WIDTH - 1)


def add(curve, left, right):
    """Complete affine reference arithmetic, independent of Circom witnesses."""
    if left is None:
        return right
    if right is None:
        return left
    p = curve["prime"]
    x, y = left
    xx, yy = right
    if x == xx:
        if (y + yy) % p == 0:
            return None
        slope = (3*x*x + curve["a"]) * pow(2*y, -1, p) % p
    else:
        slope = (yy-y) * pow(xx-x, -1, p) % p
    rx = (slope*slope-x-xx) % p
    return rx, (slope*(x-rx)-y) % p


def multiply(curve, scalar, point):
    result = None
    while scalar:
        if scalar & 1:
            result = add(curve, result, point)
        point = add(curve, point, point)
        scalar >>= 1
    return result


def table(curve, base):
    """table[j] = [(2*j+1) * 2**(12*window)]G."""
    step = add(curve, base, base)
    point = base
    result = []
    for _ in range(ENTRIES):
        assert point is not None
        x, y = point
        assert 0 <= x < curve["prime"] and 0 < y < curve["prime"]
        assert (y*y-x*x*x-curve["a"]*x-curve["b"]) % curve["prime"] == 0
        result.append(limbs(x) + limbs(y))
        point = add(curve, point, step)
    return result


def generate(destination):
    with destination.open("w") as output:
        output.write(
            "pragma circom 2.2.0;\n\n"
            "// Generated by comb_generator.py. Each entry contains x then y,\n"
            "// each in 22 little-endian 12-bit limbs. No field reduction of\n"
            "// the 256-bit coordinates occurs during Circom compilation.\n"
            "// table_w[j] = [(2*j+1) * 2^(12*w)]G.\n\n"
            "function kb_comb_table(p256, window) {\n"
            "    var out[2048][44];\n"
        )
        for p256, curve in enumerate(CURVES):
            output.write(f"    if (p256 == {p256}) {{\n")
            base = (curve["gx"], curve["gy"])
            assert multiply(curve, curve["order"], base) is None
            for window in range(WINDOWS):
                output.write(f"        if (window == {window}) {{\n")
                output.write("            out = [\n")
                for index, row in enumerate(table(curve, base)):
                    suffix = "," if index+1 < ENTRIES else ""
                    output.write("                [" + ",".join(map(str, row)) + "]" + suffix + "\n")
                output.write("            ];\n        }\n")
                for _ in range(WIDTH):
                    base = add(curve, base, base)
            output.write("    }\n")
        output.write("    return out;\n}\n")


if __name__ == "__main__":
    generate(Path(__file__).with_name("comb_constants.circom"))
